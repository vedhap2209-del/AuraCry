"""CLI:
    python manage.py init-db
    python manage.py create-admin --email E --name N [--password P]
    python manage.py seed-demo [--force]     # creates demo USER + ADMIN, writes private DEMO_CREDENTIALS.md
"""
import argparse
import os
import secrets
import string
from pathlib import Path

import db
import security as S
import validators as V


def _conn():
    db.init()
    return db.connect()


def _strong_password(n=16):
    alpha = string.ascii_letters + string.digits
    # guarantee the validator's letter+digit+length rule, then fill with random alphanumerics
    base = [secrets.choice(string.ascii_uppercase), secrets.choice(string.ascii_lowercase), secrets.choice(string.digits)]
    base += [secrets.choice(alpha) for _ in range(n - len(base))]
    secrets.SystemRandom().shuffle(base)
    return "".join(base)


def _upsert(c, name, email, pw, role, pin):
    row = c.execute("SELECT id FROM users WHERE email=?", (email.lower(),)).fetchone()
    h, ph = S.hash_password(pw), S.hash_pin(pin)
    if row:
        c.execute("UPDATE users SET role=?, status='ACTIVE', password_hash=?, pin_hash=?, name=?, failed_logins=0, locked_until=NULL WHERE id=?",
                  (role, h, ph, name, row[0]))
    else:
        c.execute("INSERT INTO users(name,email,password_hash,pin_hash,role) VALUES(?,?,?,?,?)", (name, email.lower(), h, ph, role))
    c.commit()


def create_admin(a):
    import getpass
    c = _conn()
    pw = a.password or os.environ.get("ADMIN_PASSWORD") or getpass.getpass("Admin password: ")
    pin = a.pin or os.environ.get("ADMIN_PIN") or f"{secrets.randbelow(900000) + 100000}"
    err = V.check_email(a.email) or V.check_password(pw) or V.check_pin(pin)
    if err:
        raise SystemExit(err)
    _upsert(c, a.name, a.email, pw, "ADMIN", pin)
    print(f"Admin ready: {a.email}  (login is password -> email code -> PIN {pin})")


def seed_demo(a):
    c = _conn()
    out = Path(__file__).resolve().parent.parent / "DEMO_CREDENTIALS.md"
    if out.exists() and not a.force:
        raise SystemExit(f"{out} already exists. Use --force to regenerate (this changes the demo passwords).")
    accounts = [("Demo User", "user@auracry.local", "USER"), ("Demo Admin", "admin@auracry.local", "ADMIN")]
    lines = ["# AuraCry demo credentials (PRIVATE - not committed)\n",
             "Generated by `python manage.py seed-demo`. These are for local/demo use only.",
             "Change them before any real deployment.",
             "Login is three-factor: **password -> email code -> security PIN**.",
             "Without SMTP configured the email code is printed to the server log (dev mode).\n"]
    for name, email, role in accounts:
        pw = _strong_password()
        pin = f"{secrets.randbelow(900000) + 100000}"
        _upsert(c, name, email, pw, role, pin)
        lines.append(f"## {role}\n- email: `{email}`\n- password: `{pw}`\n- security PIN: `{pin}`\n")
    out.write_text("\n".join(lines))
    os.chmod(out, 0o600)
    print(f"Seeded demo USER + ADMIN. Credentials written to {out} (chmod 600).")
    print("Remember: without SMTP configured, the OTP is printed to the server log (dev mode).")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("init-db")
    p = sub.add_parser("create-admin")
    p.add_argument("--email", required=True); p.add_argument("--name", default="Admin"); p.add_argument("--password"); p.add_argument("--pin")
    ps = sub.add_parser("seed-demo"); ps.add_argument("--force", action="store_true")
    a = ap.parse_args()
    if a.cmd == "init-db":
        db.init(); print("Database ready.")
    elif a.cmd == "seed-demo":
        seed_demo(a)
    else:
        create_admin(a)
